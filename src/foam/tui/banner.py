#: 未收录字符的兜底字形(问号块)。
_FALLBACK: tuple[str, ...] = (" ███ ", "█   █", "  ██ ", "     ", "  █  ")


def render_wordmark(text: str) -> list[str]:
    """把文本渲染为大号字标,返回 5 行字符串(行间已是视觉对齐的等宽块)。"""
    rows = [""] * GLYPH_ROWS
    for ch in text.upper():
        glyph = _GLYPHS.get(ch, _FALLBACK)
        for i in range(GLYPH_ROWS):
            rows[i] += glyph[i] + "  "
    return [row.rstrip() for row in rows]
